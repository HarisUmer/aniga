"""Look up every seeded title on AniList and write cover/banner/colour updates as SQL.

Reads the titles straight from infra/db/init/002_seed.sql so the seed stays the single source of truth.
Output: infra/db/init/004_media_art.sql (UPDATEs keyed by external_id).

Country filter keeps manhwa (KR) and manhua (CN) from matching a Japanese title with the same name.
AniList's public API needs no key. Its limit is 90/min nominally but often degraded to 30/min,
so requests are spaced ~2 s apart and 429 responses honour Retry-After.
"""

from __future__ import annotations

import json
import re
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SEED = ROOT / "infra" / "db" / "init" / "002_seed.sql"
OUT = ROOT / "infra" / "db" / "init" / "004_media_art.sql"

QUERY = """
query ($search: String, $type: MediaType, $country: CountryCode, $format: [MediaFormat]) {
  Media(search: $search, type: $type, countryOfOrigin: $country, format_in: $format, sort: [SEARCH_MATCH, POPULARITY_DESC]) {
    id
    title { romaji english }
    coverImage { extraLarge color }
    bannerImage
    averageScore
  }
}
"""

# English titles that AniList's fuzzy search resolves to the wrong entry; searched by romaji instead.
SEARCH_OVERRIDES = {
    "a-kny": "Kimetsu no Yaiba",
    "w-orv": "Jeonjijeok Dokja Sijeom",
    "h-mdzs": "Mo Dao Zu Shi",
    "h-tka": "Quanzhi Gaoshou",
    "h-tdg": "Yao Shen Ji",
    "h-soulland": "Douluo Dalu",
}

TYPE_MAP = {"ANIME": ("ANIME", None), "MANGA": ("MANGA", "JP"), "MANHWA": ("MANGA", "KR"), "MANHUA": ("MANGA", "CN")}
ROW = re.compile(r"^\('(?P<type>ANIME|MANGA|MANHWA|MANHUA)', '(?P<title>(?:[^']|'')+)',.*'seed', '(?P<ext>[^']+)'\)", re.M)


def lookup(title: str, media_type: str, use_country: bool = True) -> dict | None:
    al_type, country = TYPE_MAP[media_type]
    if not use_country:
        country = None
    # Seeded anime are all TV series; restricting format stops shorts/specials winning the fuzzy match.
    variables = {"search": title, "type": al_type, "format": ["TV"] if al_type == "ANIME" else ["MANGA"]}
    if country:
        variables["country"] = country
    body = json.dumps({"query": QUERY, "variables": variables}).encode()
    for attempt in range(5):
        req = urllib.request.Request("https://graphql.anilist.co", data=body, method="POST",
                                     headers={"Content-Type": "application/json", "Accept": "application/json",
                                              "User-Agent": "Aniga/0.1 (practice project)"})
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return json.loads(resp.read())["data"]["Media"]
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return None
            if e.code == 429:
                wait = int(e.headers.get("Retry-After", "30")) + 1
                print(f"  rate limited, waiting {wait}s")
                time.sleep(wait)
                continue
            raise
    raise RuntimeError("AniList kept rate limiting")


def lit(v) -> str:
    return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    rows = [(m["type"], m["title"].replace("''", "'"), m["ext"]) for m in ROW.finditer(SEED.read_text(encoding="utf-8"))]
    lines = ["-- GENERATED by tools/media-sync/fetch_anilist_art.py from AniList. Do not edit by hand."]
    missing = []
    for media_type, title, ext in rows:
        m = lookup(SEARCH_OVERRIDES.get(ext, title), media_type)
        time.sleep(2.2)
        if not m and media_type != "ANIME":
            # Some webcomics are filed under a different country (e.g. TBATE is US-written, KR-drawn).
            m = lookup(SEARCH_OVERRIDES.get(ext, title), media_type, use_country=False)
            time.sleep(2.2)
        if not m:
            missing.append(title)
            continue
        matched = m["title"]["english"] or m["title"]["romaji"]
        print(f"{media_type:7} {title:40} -> {matched} (#{m['id']}, colour {m['coverImage']['color']})")
        lines.append(
            f"UPDATE media SET cover_url = {lit(m['coverImage']['extraLarge'])}, banner_url = {lit(m['bannerImage'])}, "
            f"accent_color = {lit(m['coverImage']['color'])}, anilist_id = {m['id']}, average_score = {lit(m['averageScore'])} "
            f"WHERE external_source = 'seed' AND external_id = {lit(ext)};  -- matched: {matched}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(rows) - len(missing)}/{len(rows)} -> {OUT}")
    if missing:
        print("no match:", missing)


if __name__ == "__main__":
    main()
